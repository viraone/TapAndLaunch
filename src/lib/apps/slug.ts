/** `Maple Street Bakery` -> `maple-street-bakery`: lowercase letters, numbers and hyphens, at most 63 characters. */
export function slugify(value: string): string {
  return value
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 63)
    .replace(/-+$/g, "");
}
